export const AFRICAN_COUNTRIES_MAP: Map<string, AfricanCountry> = new Map(
  AFRICAN_COUNTRIES.map((c) => [c.name.toLowerCase(), c])
);

export function detectCountry(text: string): string {
  const lower = text.toLowerCase();
  for (const country of AFRICAN_COUNTRIES) {
    for (const keyword of country.keywords) {
      if (lower.includes(keyword)) {
        return country.name;
      }
    }
  }
  return "";
}

export function getCountryKeywords(countryName: string): string[] {
  const country = AFRICAN_COUNTRIES_MAP.get(countryName.toLowerCase());
  return country ? country.keywords : [countryName.toLowerCase()];
}

